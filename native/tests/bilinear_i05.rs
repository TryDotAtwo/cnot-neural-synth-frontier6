use cnot103_native::{
    register_bilinear_contexts, BilinearContext, FeatureId, FeaturePolicy, FeatureRegistry,
    FeatureRole, FeatureStatus, MatrixState,
};

fn id(text: &str) -> FeatureId {
    FeatureId::new(text.as_bytes()[0], text[1..].parse().unwrap()).unwrap()
}

fn policy() -> FeaturePolicy {
    FeaturePolicy {
        enabled_ids: vec![id("I05")],
        seed: 0,
        schema_id: "i05-stage55-fixture-v1".into(),
        solver_assisted: false,
        symmetry_contract: "augmentation_only".into(),
        evaluations: None,
        max_bytes: None,
    }
}

fn one_port_context() -> BilinearContext {
    // U=[1 0], V=[1;0], A0=[1], D0=[0].  For the selected
    // physical entry C=0/1, the exact stage-55 reduction yields
    // residual rank 0/1 and one free hidden coordinate.
    BilinearContext::new(
        2,
        vec![1],
        vec![0],
        2,
        vec![vec![1]],
        vec![vec![1], vec![0]],
        1,
        vec![vec![1]],
        vec![vec![0]],
    )
    .unwrap()
}

fn context_from_masks(u: u64, v: u64, a0: u64, d0: u64) -> BilinearContext {
    BilinearContext::new(
        2,
        vec![1],
        vec![0],
        2,
        vec![vec![u]],
        vec![vec![v & 1], vec![(v >> 1) & 1]],
        1,
        vec![vec![a0]],
        vec![vec![d0]],
    )
    .unwrap()
}

#[test]
fn i05_matches_hand_derived_stage55_residual_rank_and_hidden_width() {
    let mut registry = FeatureRegistry::new();
    register_bilinear_contexts(&mut registry, vec![one_port_context()], 144, 100_000).unwrap();

    let identity = MatrixState::from_packed_rows(2, "all_to_all_unit_cnot:2", vec![1, 2]).unwrap();
    let one_cnot = MatrixState::from_packed_rows(2, "all_to_all_unit_cnot:2", vec![1, 3]).unwrap();
    let packet = registry.build(&[identity, one_cnot], &policy()).unwrap();
    let feature = packet.feature(id("I05"));

    assert_eq!(feature.spec.role, FeatureRole::Global);
    assert_eq!(feature.spec.channels, 2);
    assert_eq!(feature.shape, vec![2, 2]);
    assert_eq!(feature.status, vec![FeatureStatus::Computed; 2]);
    assert_eq!(feature.values, vec![0.0, 1.0, 1.0, 1.0]);
}

#[test]
fn i05_matches_stage55_source_golden_values_across_port_ranks() {
    // Exhaustive n=2 goldens were generated by the pinned stage55_bilinear_kernel.py
    // port_reduce implementation (SHA-256 30c90c396e8f5f1d43921f09a0d07ca723afa6e38a9c0ebed4f68b5b2aab5353).
    // Loop order is c, U row mask, V column mask, A0 bit, D0 bit.
    let expected_rank = "000100000001000000010001000100010000111010001110100011101110111011101000";
    let expected_hidden =
        "111100001111000011111111111111110000111100001111000011111111111111110000";
    let mut case = 0;
    for c in 0..2 {
        for u in 1..4 {
            for v in 1..4 {
                for a0 in 0..2 {
                    for d0 in 0..2 {
                        let mut registry = FeatureRegistry::new();
                        register_bilinear_contexts(
                            &mut registry,
                            vec![context_from_masks(u, v, a0, d0)],
                            144,
                            100_000,
                        )
                        .unwrap();
                        let state = MatrixState::from_packed_rows(
                            2,
                            "all_to_all_unit_cnot:2",
                            vec![1, 2 | c],
                        )
                        .unwrap();
                        let expected = vec![
                            f32::from(expected_rank.as_bytes()[case] - b'0'),
                            f32::from(expected_hidden.as_bytes()[case] - b'0'),
                        ];
                        let packet = registry.build(&[state], &policy()).unwrap();
                        assert_eq!(packet.feature(id("I05")).values, expected);
                        case += 1;
                    }
                }
            }
        }
    }
    assert_eq!(case, 72);
}

#[test]
fn i05_paired_rank_precedes_the_final_hidden_dimension_subtractions() {
    let context = BilinearContext::new(
        2,
        vec![1],
        vec![0],
        2,
        vec![vec![1], vec![2]],
        vec![vec![1], vec![2]],
        2,
        vec![vec![1], vec![0]],
        vec![vec![1]],
    )
    .unwrap();
    let mut registry = FeatureRegistry::new();
    register_bilinear_contexts(&mut registry, vec![context], 144, 100_000).unwrap();
    let state = MatrixState::identity(2, "all_to_all_unit_cnot:2").unwrap();
    let packet = registry.build(&[state], &policy()).unwrap();

    // Pinned stage55 source returns residual rank 1 and hidden dimension 0.
    assert_eq!(packet.feature(id("I05")).values, vec![1.0, 0.0]);
}

#[test]
fn i05_fails_closed_for_width_and_symmetry_contract_mismatches() {
    let state = MatrixState::identity(2, "all_to_all_unit_cnot:2").unwrap();
    let mut limited = FeatureRegistry::new();
    register_bilinear_contexts(&mut limited, vec![one_port_context()], 1, 100_000).unwrap();
    let packet = limited.build(&[state.clone()], &policy()).unwrap();
    assert_eq!(
        packet.feature(id("I05")).status,
        vec![FeatureStatus::ResourceLimit]
    );

    let mut registry = FeatureRegistry::new();
    register_bilinear_contexts(&mut registry, vec![one_port_context()], 144, 100_000).unwrap();
    let mut exact_relabel = policy();
    exact_relabel.symmetry_contract = "exact_relabel".into();
    assert!(registry.selected_specs(&exact_relabel).is_err());

    let no_context_width = MatrixState::identity(3, "all_to_all_unit_cnot:3").unwrap();
    let packet = registry.build(&[no_context_width], &policy()).unwrap();
    assert_eq!(
        packet.feature(id("I05")).status,
        vec![FeatureStatus::Unsupported]
    );
}

#[test]
fn i05_context_rejects_dependent_ports_and_registration_rejects_duplicate_widths() {
    assert!(BilinearContext::new(
        2,
        vec![1],
        vec![0],
        2,
        vec![vec![1], vec![1]],
        vec![vec![1], vec![0]],
        1,
        vec![vec![1], vec![0]],
        vec![vec![0]],
    )
    .is_err());

    let context = one_port_context();
    let mut registry = FeatureRegistry::new();
    assert!(register_bilinear_contexts(
        &mut registry,
        vec![context.clone(), context],
        144,
        100_000,
    )
    .is_err());
}
