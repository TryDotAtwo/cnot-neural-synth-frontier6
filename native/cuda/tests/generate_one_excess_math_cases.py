"""Independent Python-integer oracles for Stage38 CUDA arithmetic.

Only tests use these constants. Production allocates a dimension-derived limb
capacity; it does not upload counts, factors or numeric lookup tables.
"""
from pathlib import Path
from math import factorial
import random
import sys


def capacity(n):
    if not 2 <= n <= 1 << 24:
        return 0
    k = n + 1
    bits = (1 + 2 * n.bit_length() + k + 2 * k * k.bit_length()
            + (k + 1) * (3 * n).bit_length())
    return (bits + 31) // 32 + 1


def generate():
    rows = []

    def case(op, limbs, a, b=0, small=0, sa=1, sb=1):
        mask = (1 << (32 * limbs)) - 1
        assert 0 <= a <= mask and 0 <= b <= mask
        sign, remainder, comparison = 0, 0, 0
        if op == 0:
            result = a + b
        elif op == 1:
            result = a - b
        elif op == 2:
            result = a * b
        elif op == 3:
            result = a * small
        elif op == 4:
            result, remainder = divmod(a, small) if small else (0, 0)
        elif op == 5:
            signed = sa * a + sb * b
            sign = (signed > 0) - (signed < 0)
            result = abs(signed)
        elif op == 6:
            comparison = (a > b) - (a < b)
            result = a
        elif op == 7:
            result = small
        elif op == 8:
            result = 0
        else:
            raise ValueError(op)
        ok = 0 <= result <= mask and (op != 4 or small != 0)
        rows.append((op, limbs, small, sa, sb, int(ok), sign, remainder,
                     comparison, a, b, result & mask))

    rng = random.Random(0xF08B161)
    for limbs in [1, 2, 4, 8, 17, 33, 65, capacity(144), capacity(1024)]:
        maximum = (1 << (32 * limbs)) - 1
        half = 1 << (32 * limbs - 1)
        pairs = [(0, 0), (0, maximum), (maximum, 1), (maximum, maximum),
                 (half - 1, half), (half, half), (maximum - 1, 2),
                 (min(maximum, (1 << 64) - 1), 1)]
        for a, b in pairs:
            for op in [0, 1, 2, 6]:
                case(op, limbs, a, b)
            for sa, sb in [(1, 1), (-1, -1), (-1, 1), (1, -1)]:
                case(5, limbs, a, b, sa=sa, sb=sb)
        for a in [0, 1, maximum, half + 1]:
            for small in [0, 1, 2, 31, 0x80000000, 0xffffffff]:
                case(3, limbs, a, small=small)
                case(4, limbs, a, small=small)
        case(7, limbs, maximum, small=0xffffffff)
        case(8, limbs, maximum)
    for _ in range(160):
        limbs = rng.choice([1, 2, 4, 8, 17, 33, 65, capacity(144)])
        a = rng.getrandbits(rng.randrange(32 * limbs + 1))
        b = rng.getrandbits(rng.randrange(32 * limbs + 1))
        for op in [0, 1, 2, 6]:
            case(op, limbs, a, b)
        case(5, limbs, a, b, sa=rng.choice([-1, 1]), sb=rng.choice([-1, 1]))
        small = rng.randrange(1, 1 << 32)
        case(3, limbs, a, small=small)
        case(4, limbs, a, small=small)
    # Explicit signed-zero inputs: output must always use the canonical sign.
    for sa in [-1, 0, 1]:
        for sb in [-1, 0, 1]:
            case(5, 4, 0, 0, sa=sa, sb=sb)

    lines = ["// Generated by generate_one_excess_math_cases.py using Python integers.",
             "#pragma once", "#include <cstdint>",
             "struct OneExcessMathCase { unsigned op,limbs,small; int sa,sb,ok,sign; unsigned remainder; int comparison; const char *a,*b,*expected; };",
             "static const OneExcessMathCase one_excess_math_cases[] = {"]
    for row in rows:
        fields = ",".join(str(v) + ("U" if i in [0, 1, 2, 7] else "")
                          for i, v in enumerate(row[:9]))
        lines.append("    {" + fields + "," + ",".join(f'"{v:x}"' for v in row[9:]) + "},")
    lines.extend(["};", "struct OneExcessCapacityCase { unsigned n,limbs; };",
                  "static constexpr OneExcessCapacityCase one_excess_capacity_cases[] = {"])
    dims = [0, 1, *range(2, 257), 511, 512, 513, 1023, 1024, 1025,
            65535, 65536, (1 << 24) - 1, 1 << 24, (1 << 24) + 1, 0xffffffff]
    for n in dims:
        size = capacity(n)
        if 2 <= n <= 1025:
            k = n + 1
            # Evaluate the bound with arbitrary integers, not floating logs.
            upper = 2 * n * n * (1 << k) * k ** (2 * k) * (3 * n) ** (k + 1)
            assert upper.bit_length() < 32 * size
        lines.append(f"    {{{n}U,{size}U}},")
    lines.extend(["};", "struct OneExcessDifferenceCase { unsigned m,limbs; const char *factorial,*multinomial; };",
                  "static const OneExcessDifferenceCase one_excess_difference_cases[] = {"])
    for m in [2, 3, 8, 20, 40, 64, 144]:
        f = factorial(m)
        first, second = m // 3, (m - m // 3) // 2
        value = f // (factorial(first) * factorial(second) * factorial(m - first - second))
        lines.append(f'    {{{m}U,{capacity(max(2, m - 1))}U,"{f:x}","{value:x}"}},')
    lines.extend(["};", ""])
    return "\n".join(lines), len(rows), len(dims)


if __name__ == "__main__":
    generated, count, bounds = generate()
    path = Path(__file__).with_name("one_excess_math_cases.h")
    if "--check" in sys.argv:
        assert path.read_text(encoding="utf-8") == generated, "stale exact arithmetic fixtures"
    else:
        path.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Exact integer fixtures: {count}; capacity cases: {bounds}; finite-difference cases: 7")
