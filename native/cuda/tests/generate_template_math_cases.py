"""Generate exact rational conversion fixtures using unbounded Python integers.

Unlike the CUDA fractional-bit loop, this oracle rounds a single exact scaled
quotient/remainder. Preserve the Rust source's rejection for exponent>23.
Run with --check to verify the committed header without rewriting it.
"""
from pathlib import Path
import random
import sys


def bits(n, d):
    if d == 0:
        return None
    if n == 0:
        return 0
    exponent = n.bit_length() - d.bit_length()
    if (n < (d << exponent)) if exponent >= 0 else ((n << -exponent) < d):
        exponent -= 1
    if exponent > 23:
        return None
    subnormal = exponent < -126
    shift = 149 if subnormal else 23 - exponent
    q, r = divmod(n << shift, d)
    q += (2 * r > d) or (2 * r == d and q % 2 == 1)
    if subnormal:
        assert q <= 1 << 23
        return q
    if q >= 1 << 24:
        q >>= 1
        exponent += 1
    return ((exponent + 127) << 23) | (q - (1 << 23))


def generate():
    maximum = (1 << 128) - 1
    cases = [(n, d) for n in range(32) for d in range(18)]
    for value in [0, 1, 2, (1 << 63) - 1, 1 << 63, (1 << 64) - 1,
                  1 << 64, (1 << 127) - 1, 1 << 127, maximum]:
        cases.extend([(value, maximum), (maximum, value), (value, value)])
    for exponent in [-126, -100, -63, -1, 0, 1, 23]:
        for offset in [0, 1, 2, 3, (1 << 24) - 1]:
            n, d = (1 << 24) + offset, 1 << 24
            if exponent >= 0:
                n <<= exponent
            else:
                d <<= -exponent
            if n <= maximum and d <= maximum:
                cases.append((n, d))
    rng = random.Random(0xE020306070809)
    for _ in range(512):
        cases.append((rng.getrandbits(rng.randrange(1, 129)),
                      rng.getrandbits(rng.randrange(1, 129))))
    cases = list(dict.fromkeys(cases))
    lines = ["// Generated by generate_template_math_cases.py; independent exact quotient oracle.",
             "#pragma once", "#include <cstdint>",
             "struct TemplateRationalCase { std::uint64_t nl,nh,dl,dh; std::uint32_t bits,ok; };",
             "static constexpr TemplateRationalCase template_rational_cases[] = {"]
    mask = (1 << 64) - 1
    for n, d in cases:
        value = bits(n, d)
        lines.append("    {" + ",".join(f"0x{x:016x}ULL" for x in [n & mask, n >> 64, d & mask, d >> 64])
                     + f",0x{(value or 0):08x}U,{int(value is not None)}U}},")
    lines.extend(["};", ""])
    return "\n".join(lines), len(cases)


if __name__ == "__main__":
    text, count = generate()
    path = Path(__file__).with_name("template_response_math_cases.h")
    if "--check" in sys.argv:
        assert path.read_text(encoding="utf-8") == text, "stale rational fixtures"
    else:
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"Exact rational fixtures: {count}")
